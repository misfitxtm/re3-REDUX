#!/usr/bin/env python3
"""Generates Rust model-index tables and predicates from re3's ModelIndices.h for one game.

usage: gen_model_indices.py <src-dir> <gta3|vc> > out.rs
"""
import os, re, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import cpp_lite

src, game = sys.argv[1], sys.argv[2]
preprocess, _ = cpp_lite.make({})
text = preprocess(open(f"{src}/modelinfo/ModelIndices.h", encoding="latin-1").read())

# 1. names matched at IDE load time: X("model", MI_VAR)
macro = re.search(r"#define MODELINDICES(.*?)\n\n", text + "\n\n", re.S).group(1)
dynamic = re.findall(r'X\(\s*"([^"]*)"\s*,\s*(\w+)\s*\)', macro)
dyn_vars = {v for _, v in dynamic}
assert len(dyn_vars) == len(dynamic), "duplicate model-index variable"

# 2. hardcoded ids: the anonymous enum containing MI_PLAYER
enum_body = re.search(r"enum\s*\{\s*(MI_PLAYER.*?)\}", text, re.S).group(1)
hard, values, nxt = [], {}, 0
for item in [x.strip() for x in enum_body.split(",") if x.strip()]:
    name, _, val = item.partition("=")
    name, val = name.strip(), val.strip()
    if val:
        nxt = values[val] if val in values else int(val, 0)
    values[name] = nxt
    hard.append((name, nxt))
    nxt += 1

# 3. predicates made only of `id == X ||` terms and calls to other predicates
preds = []
for m in re.finditer(r"inline bool\s*(\w+)\s*\(int16 id\)\s*\{(.*?)\n\}", text, re.S):
    name, body = m.groups()
    body = body.strip()
    snake = re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()
    if m := re.fullmatch(r"return\s*id >= (\w+) && id <= (\w+);", body):
        lo, hi = m.groups()
        preds.append((name, snake, f"id >= {{{lo}}} && id <= {{{hi}}}"))
        continue
    if not re.fullmatch(r"return\s*([\w\s=|(),&!]+);", body) or "CModelInfo" in body or "mi->" in body:
        preds.append((name, snake, None))  # hand-written
        continue
    terms = [t.strip() for t in body.removeprefix("return").rstrip(";").split("||")]
    out = []
    for t in terms:
        if (mm := re.fullmatch(r"id == (\w+)", t)):
            out.append(("eq", mm.group(1)))
        elif (mm := re.fullmatch(r"(\w+)\(id\)", t)):
            out.append(("call", mm.group(1)))
        else:
            out = None
            break
    preds.append((name, snake, out))


def rust_name(v):
    return v.removeprefix("MI_") if v.startswith("MI_") else v


print("// @generated by tools/gen_model_indices.py from the original source. Do not edit.")
print("#![allow(dead_code, clippy::manual_range_contains)]\n")
print(f"/// Model names the IDE loader matches to ids at load time: (model name, variable).")
print(f"pub static DYNAMIC_NAMES: [(&str, &str); {len(dynamic)}] = [")
for n, v in dynamic:
    print(f'    ("{n}", "{v}"),')
print("];\n")
print("/// Slots in [`ModelIndices`] for the names above.")
print("pub mod slot {")
for i, (_, v) in enumerate(dynamic):
    print(f"    pub const {rust_name(v)}: usize = {i};")
print("}\n")
print("/// Hardcoded model ids.")
print("pub mod mi {")
for n, v in hard:
    ty = "i16"
    print(f"    pub const {rust_name(n)}: {ty} = {v};")
print("}\n")
print(f"pub const DYNAMIC_COUNT: usize = {len(dynamic)};\n")
print("#[derive(Debug, Clone)]\npub struct ModelIndices {\n    ids: [i16; DYNAMIC_COUNT],\n}\n")
print("impl Default for ModelIndices {\n    fn default() -> Self {\n        Self { ids: [-1; DYNAMIC_COUNT] }\n    }\n}\n")
print("impl ModelIndices {")
print("    /// `InitModelIndices`: forget all matches.\n    pub fn reset(&mut self) {\n        self.ids = [-1; DYNAMIC_COUNT];\n    }\n")
print("    /// `MatchModelString`: record `id` if `name` is one of the tracked models (exact match).\n    pub fn match_model_string(&mut self, name: &str, id: i16) -> bool {\n        match DYNAMIC_NAMES.iter().position(|(n, _)| *n == name) {\n            Some(i) => {\n                self.ids[i] = id;\n                true\n            }\n            None => false,\n        }\n    }\n")
print("    /// Id matched for slot `s` (see [`slot`]), or -1.\n    pub fn get(&self, s: usize) -> i16 {\n        self.ids[s]\n    }\n")


def operand(v):
    return f"self.get(slot::{rust_name(v)})" if v in dyn_vars else f"mi::{rust_name(v)}"


hand = []
for name, snake, terms in preds:
    if terms is None:
        hand.append(name)
        continue
    if isinstance(terms, str):
        expr = terms.format(**{k: operand(k) for k in re.findall(r"\{(\w+)\}", terms)})
    else:
        expr = " || ".join(f"id == {operand(a)}" if k == "eq" else f"self.{re.sub(r'(?<!^)(?=[A-Z])', '_', a).lower()}(id)" for k, a in terms)
    print(f"    pub fn {snake}(&self, id: i16) -> bool {{\n        {expr}\n    }}\n")
print("}")
if hand:
    print("// hand-written elsewhere: " + ", ".join(hand))

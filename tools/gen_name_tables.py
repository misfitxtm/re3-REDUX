#!/usr/bin/env python3
"""Generates name -> id tables (vehicle handling names, ped types) from re3's sources for one game.

usage: gen_name_tables.py <src-dir> > out.rs
"""
import os, re, sys

src = sys.argv[1]
handling = open(f"{src}/vehicles/HandlingMgr.cpp", encoding="latin-1").read()
body = re.search(r"VehicleNames\[NUMHANDLINGS\]\[14\]\s*=\s*\{(.*?)\};", handling, re.S).group(1)
vehicles = re.findall(r'"([^"]*)"', body)

ped_h = open(f"{src}/peds/PedType.h", encoding="latin-1").read()
enum = re.sub(r"//[^\n]*", "", re.search(r"enum ePedType\s*\{(.*?)\};", ped_h, re.S).group(1))
ids = [x.strip() for x in enum.split(",") if x.strip() and not x.strip().startswith("NUM_")]
ped_c = open(f"{src}/peds/PedType.cpp", encoding="latin-1").read()
fn = re.search(r"CPedType::FindPedType\(char \*type\)\s*\{(.*?)\n\}", ped_c, re.S).group(1)
names = [(n, ids.index(i)) for n, i in re.findall(r'strcmp\(type, "(\w+)"\) == 0\) return (\w+);', fn)]

print("// @generated by tools/gen_name_tables.py from the original source. Do not edit.\n")
print(f"/// Vehicle handling names in `VehicleNames` order; the index is the handling id.")
print(f"pub static HANDLING_NAMES: [&str; {len(vehicles)}] = [")
for v in vehicles:
    print(f'    "{v}",')
print("];\n")
print("/// `FindPedType`: ped type name -> `ePedType` value.")
print(f"pub static PED_TYPES: [(&str, i32); {len(names)}] = [")
for n, i in names:
    print(f'    ("{n}", {i}),')
print("];")
print(f"\npub const NUM_PED_TYPES: i32 = {len(ids)};")

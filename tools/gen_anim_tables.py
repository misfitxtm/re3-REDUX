#!/usr/bin/env python3
"""Generates Rust animation tables from re3's AnimationId.h / AnimManager.{h,cpp} for one game.

usage: gen_anim_tables.py <src-dir> <gta3|vc> > out.rs
"""
import os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

src, game = sys.argv[1], sys.argv[2]
DEFINES = {"gta3": {"GTA_VERSION": 311, "GTA3_PS2_160": 301, "PC_PLAYER_CONTROLS": 1},
           "vc": {"GTA_VERSION": 411, "PC_PLAYER_CONTROLS": 1}}[game]


import cpp_lite

preprocess, strip_comments = cpp_lite.make(DEFINES)


def read(name):
    return preprocess(open(f"{src}/animation/{name}", encoding="latin-1").read())


ids_h, mgr_h, mgr_c, assoc_h = read("AnimationId.h"), read("AnimManager.h"), read("AnimManager.cpp"), read("AnimBlendAssociation.h")


def enum_items(text, name):
    body = re.search(r"enum\s+" + name + r"\s*\{(.*?)\}", text, re.S).group(1)
    items, nxt = [], 0
    for it in [x.strip() for x in body.split(",") if x.strip()]:
        n, _, v = it.partition("=")
        if v.strip():
            known = dict(items)
            nxt = known[v.strip()] if v.strip() in known else int(v.strip(), 0)
        items.append((n.strip(), nxt))
        nxt += 1
    return items


anim_ids = enum_items(ids_h, "AnimationId")
groups = enum_items(mgr_h, "AssocGroupId")
flags = dict(re.findall(r"(ASSOC_\w+)\s*=\s*(0x[0-9a-fA-F]+|\d+)", assoc_h))
flags = {k: int(v, 0) for k, v in flags.items()}
idx = dict(anim_ids)


def flag_value(expr):
    v = 0
    for part in expr.split("|"):
        part = part.strip()
        if part:
            v |= flags[part]
    return v


descs = {}
for m in re.finditer(r"AnimAssocDesc\s+(\w+)\s*\[\]\s*=\s*\{(.*?)\n\};", mgr_c, re.S):
    entries = re.findall(r"\{\s*(ANIM_\w+)\s*,([^}]*)\}", m.group(2))
    descs[m.group(1)] = [(idx[a], flag_value(f)) for a, f in entries]

names = {}
for m in re.finditer(r"(?:char const|const char)\s*\*\s*(\w+)\s*\[\]\s*=\s*\{(.*?)\};", mgr_c, re.S):
    names[m.group(1)] = re.findall(r'"([^"]*)"', m.group(2))

defs_body = re.search(r"ms_aAnimAssocDefinitions\[NUM_ANIM_ASSOC_GROUPS\]\s*=\s*\{(.*?)\n\};", mgr_c, re.S).group(1)
defs = []
for m in re.finditer(r'\{\s*"([^"]*)"\s*,\s*"([^"]*)"\s*,\s*(\w+)\s*,\s*(?:awc\((\w+)\)|(\d+)\s*,\s*(\w+))\s*,\s*(\w+)\s*\}', defs_body):
    name, block, model, awc, count, arr, desc = m.groups()
    arr = awc or arr
    n = names[arr] if awc else names[arr][: int(count)]
    d = descs[desc]
    assert len(d) >= len(n), (name, len(n), len(d))  # extra descriptors are simply unused
    defs.append((name, block, n, d[: len(n)]))

assert len(defs) == len(groups) - 1, (len(defs), len(groups))  # last entry is the NUM_ count

print("// @generated by tools/gen_anim_tables.py from the original source. Do not edit.")
print("#![allow(dead_code)]\n")
print("pub mod anim {")
for n, v in anim_ids:
    print(f"    pub const {n.removeprefix('ANIM_')}: u32 = {v};")
print("}\n")
print("pub mod assoc {")
for n, v in flags.items():
    print(f"    pub const {n.removeprefix('ASSOC_')}: u32 = {v:#x};")
print("}\n")
print("pub mod group {")
for n, v in groups:
    print(f"    pub const {n.removeprefix('ASSOCGRP_').removeprefix('NUM_ANIM_ASSOC_GROUPS') or 'COUNT'}: usize = {v};" if n != "NUM_ANIM_ASSOC_GROUPS" else f"    pub const COUNT: usize = {v};")
print("}\n")
print("pub struct GroupDef {\n    pub name: &'static str,\n    pub block: &'static str,\n    pub anims: &'static [&'static str],\n    /// (animation id, association flags) per entry of `anims`\n    pub descs: &'static [(u32, u32)],\n}\n")
print("pub static GROUPS: &[GroupDef] = &[")
for name, block, n, d in defs:
    anims = ", ".join(f'"{a}"' for a in n)
    ds = ", ".join(f"({i}, {f:#x})" for i, f in d)
    print(f'    GroupDef {{ name: "{name}", block: "{block}", anims: &[{anims}], descs: &[{ds}] }},')
print("];")

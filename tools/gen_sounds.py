#!/usr/bin/env python3
"""Generates crates/re3-core/src/audio/sound_list.rs from the C++ soundlist.h (eSound and eScriptSound)."""
import re, sys
src = open(sys.argv[1]).read()
out = ["// @generated by tools/gen_sounds.py from the original source. Do not edit.", "#![allow(dead_code)]", ""]
for enum, mod, prefix in re.findall(r"enum\s+(eSound|eScriptSound)\s*\{(.*?)\};", src, re.S) and [(m.group(1), m.group(1), None) for m in re.finditer(r"enum\s+(\w+)", src)]:
    pass
for m in re.finditer(r"enum\s+(\w+)\s*\{(.*?)\};", src, re.S):
    name, body = m.group(1), m.group(2)
    mod = {"eSound": "sound", "eScriptSounds": "script_sound"}.get(name, name.lower())
    out.append(f"pub mod {mod} {{")
    n = 0
    for item in body.split(","):
        item = re.sub(r"//.*", "", item).strip()
        if not item:
            continue
        if "=" in item:
            k, v = [s.strip() for s in item.split("=")]
            n = int(v, 0)
        else:
            k = item
        const = re.sub(r"^(SCRIPT_)?SOUND_", "", k)
        if const[0].isdigit():
            const = "_" + const
        out.append(f"    pub const {const}: u16 = {n};")
        n += 1
    out.append("}")
    out.append("")
open(sys.argv[2], "w").write("\n".join(out))
